ОБРАЗЕЦ_КОЛОНКИ = 'ДокументыЗаказаВид'


def колонка(таблица, поле, заголовки, ширина=None):
    e = копия(ОБРАЗЕЦ_КОЛОНКИ)
    переименовать(e, ОБРАЗЕЦ_КОЛОНКИ, таблица + поле)
    задать_локализацию(e, 'title', заголовки, после='id')
    путь_данных(e, f'{таблица}.{поле}')
    ext = e.find('extInfo')
    w = ext.find('width')
    if ширина is None:
        ext.remove(w)
        ext.find('autoMaxWidth').text = 'true'
    else:
        w.text = str(ширина)
    return e


def таблица(имя, колонки, высота, обработчики_таблицы):
    e = копия('ДокументыЗаказа', без_детей=True)
    переименовать(e, 'ДокументыЗаказа', имя)
    путь_данных(e, имя)
    обработчики(e, обработчики_таблицы)
    e.find('heightInTableRows').text = str(высота)
    позиция = list(e).index(e.find('changeRowSet'))
    for i, (поле, заголовки, ширина) in enumerate(колонки):
        e.insert(позиция + i, колонка(имя, поле, заголовки, ширина))
    return e


ОБРАЗЕЦ_ВВОДА = 'ЗаказыПоставщикуКоличествоУпаковок'
ОБРАЗЕЦ_ВЫБОРА = 'ЗаказыПоставщикуДокументПредставление'


def поле_ввода(таблица, поле, заголовки, ширина, события=(), выбор=False):
    """Колонка ввода: InputField по образцу колонки закупок; выбор - кнопка выбора без ввода текста (НачалоВыбора)."""
    имя_образца = ОБРАЗЕЦ_ВЫБОРА if выбор else ОБРАЗЕЦ_ВВОДА
    e = copy.deepcopy(найти(имя_образца))
    переименовать(e, имя_образца, таблица + поле)
    задать_локализацию(e, 'title', заголовки, после='id')
    задать_локализацию(e, 'toolTip', None)
    assert e.find('titleFont') is not None, имя_образца  # шрифт шапки колонки (colfont.py)
    путь_данных(e, f'{таблица}.{поле}')
    обработчики(e, события)
    e.find('extInfo/width').text = str(ширина)
    return e


def флажок(таблица, поле):
    e = copy.deepcopy(найти('РеквизитыОбъектаИзменять', образец_флажка))
    переименовать(e, 'РеквизитыОбъектаИзменять', таблица + поле)
    путь_данных(e, f'{таблица}.{поле}')
    for тег in ('handlers', 'headerPicture'):
        for h in e.findall(тег):
            e.remove(h)
    return e


def флажок_шапки(имя, заголовки, событие):
    """Флажок вне таблицы: колонка-флажок образца с заголовком справа."""
    e = copy.deepcopy(найти('РеквизитыОбъектаИзменять', образец_флажка))
    переименовать(e, 'РеквизитыОбъектаИзменять', имя)
    путь_данных(e, имя)
    for тег in ('handlers', 'headerPicture'):
        for h in e.findall(тег):
            e.remove(h)
    e.find('titleLocation').text = 'Right'
    задать_локализацию(e, 'title', заголовки, после='id')
    обработчики(e, [('OnChange', событие)])
    return e


def таблица_ввода(имя, колонки, высота, обработчики_таблицы, менять_состав=True):
    """Таблица с вводом строк по образцу таблицы «Заказы поставщику»: колонки - готовые элементы."""
    e = копия('ЗаказыПоставщику', без_детей=True)
    переименовать(e, 'ЗаказыПоставщику', имя)
    путь_данных(e, имя)
    панель_таблицы = e.find('autoCommandBar')
    for c in панель_таблицы.findall('items'):
        панель_таблицы.remove(c)
    обработчики(e, обработчики_таблицы)
    e.find('heightInTableRows').text = str(высота)
    e.find('changeRowSet').text = 'true' if менять_состав else 'false'
    позиция = list(e).index(e.find('changeRowSet'))
    for i, колонка_ in enumerate(колонки):
        e.insert(позиция + i, колонка_)
    return e


def страница(имя, заголовки, дети):
    e = копия('СтраницаДокументы', без_детей=True)
    переименовать(e, 'СтраницаДокументы', имя)
    задать_локализацию(e, 'title', заголовки, после='id')
    позиция = list(e).index(e.find('type'))
    for i, ребёнок in enumerate(дети):
        e.insert(позиция + i, ребёнок)
    return e


def вложить(родитель, дети):
    позиция = list(родитель).index(родитель.find('type'))
    for i, ребёнок in enumerate(дети):
        родитель.insert(позиция + i, ребёнок)
    return родитель


def фильтр(образец_поля, имя, заголовки):
    e = копия(образец_поля)
    переименовать(e, образец_поля, имя)
    задать_локализацию(e, 'title', заголовки, после='id')
    путь_данных(e, имя)
    return e


def надпись(имя, образец_надписи='НадписьЛегенда'):
    e = копия(образец_надписи)
    переименовать(e, образец_надписи, имя)
    return e


