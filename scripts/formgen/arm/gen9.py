#!/usr/bin/env python3
"""Форма рабочего места производства, редакция 9 (2.0.16.14, замечания владельца 2026-10-05).

Поверх редакции 8 (gen8.py) текстовыми преобразованиями её вывода:
- gen9_materials.py - закладка «Материалы»: явные ширины колонок, короткие заголовки с полным именем в подсказке,
  «Способ изготовления» в конце;
- gen9_panel.py - панель фильтров (переключатель вида заказа убран, клиент и продукция - справочники, стадия и период
  отгрузки), запрос списка «Заказы» (только производство, тот же текст условий, что ТекстУсловийОтборов модуля
  менеджера), пагинатор под списком по образцу форм списков документов (группа и команды Страница* берутся из формы
  списка заказов покупателя) с легендой индикатора, штатная полоса состояния просмотра у списка выключена.

Проверка: python3 gen9.py | diff - ../../../src/cf/src/DataProcessors/АРМПроизводство/Forms/Форма/Form.form
"""
import os
import re
import sys

import gen8

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.normpath(os.path.join(ЗДЕСЬ, '..', '..', '..'))
ЭТАЛОН_ПАГИНАТОРА = os.path.join(КОРЕНЬ, 'src', 'cf', 'src', 'Documents', 'ЗаказПокупателя', 'Forms', 'ФормаСписка',
                                 'Form.form')


def применить(имя, s):
    среда = {'s': s, 're': re, 'ЭТАЛОН_ПАГИНАТОРА': ЭТАЛОН_ПАГИНАТОРА}
    with open(os.path.join(ЗДЕСЬ, имя), encoding='utf-8') as f:
        exec(compile(f.read(), имя, 'exec'), среда)
    return среда['s']


def build():
    s = gen8.build()
    s = применить('gen9_materials.py', s)
    return применить('gen9_panel.py', s)


if __name__ == '__main__':
    sys.stdout.write(build())
