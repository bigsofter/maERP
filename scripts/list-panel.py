    for имя in нужные:
        b = блок(эт, 'attributes', имя)
        ид_р[0] += 1
        frag = re.sub(r'(<name>%s</name>\s*)<id>\d+</id>' % имя,
                      lambda m: m.group(1) + '<id>%d</id>' % ид_р[0], эт[b[0]:b[1]], 1)
        if имя == 'ТаблицаСостав':
            если_нет = []
            if not норм_состав['сумма']:
                если_нет.append('Сумма')
            if not норм_состав['количество']:
                если_нет.append('Количество')
            for колонка in если_нет:
                frag = re.sub(r'\s*<columns>\s*<name>%s</name>.*?</columns>' % колонка, '', frag, flags=re.S)
            поле, тип, _ = норм_состав['объект']
            if поле != 'Номенклатура':
                frag = frag.replace('<name>Номенклатура</name>', '<name>%s</name>' % поле, 1)
                frag = frag.replace('<types>CatalogRef.Номенклатура</types>', '<types>%s</types>' % тип, 1)
        добавка += '\n  ' + frag
    я = t.rindex('</attributes>') + len('</attributes>')
    t = t[:я] + добавка + t[я:]

    команды = ['СвернутьПанель', 'РазвернутьПанель', 'ПоказатьФильтры'] \
        + (['ПоказатьКлиента'] if конф['клиент'] else []) + ['ПоказатьДетали', 'СтраницаНазад', 'СтраницаВперед']
    ид_к = [0]
    добавка = ''
    for имя in команды:
        b = блок(эт, 'formCommands', имя)
        ид_к[0] += 1
        добавка += '\n  ' + re.sub(r'<id>\d+</id>', '<id>%d</id>' % ид_к[0], эт[b[0]:b[1]], 1)
    if '</formCommands>' in t:
        я = t.rindex('</formCommands>') + len('</formCommands>')
    else:
        я = t.rindex('</attributes>') + len('</attributes>')
    t = t[:я] + добавка + t[я:]
    return p, t


