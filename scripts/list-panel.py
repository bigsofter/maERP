def состав_конфига(конф):
    """Состав документа в едином виде: чем описана строка, есть ли количество и сумма.

    Кортеж ('ТЧТовары', 'СуммаСНДС') - товарный состав по умолчанию; словарь задаёт
    свой объект строки, например сотрудника в зарплатных документах."""
    с = конф['состав']
    if not с:
        return None
    if isinstance(с, dict):
        готово = dict(объект=('Номенклатура', 'CatalogRef.Номенклатура', ПОДПИСИ['Номенклатура']),
                      количество=True, сумма=None)
        готово.update(с)
        return готово
    тч, сумма = с
    return dict(тч=тч, объект=('Номенклатура', 'CatalogRef.Номенклатура', ПОДПИСИ['Номенклатура']),
                количество=True, сумма=сумма)


def читать(p):
    return Path(p).read_text(encoding='utf-8')


def нстр(значения, хвост=': %1'):
    """НСтр на четырёх языках; апостроф внутри значения удваивается, иначе он
    закрывает строковый литерал BSL (fr = 'Date d''expédition')."""
    части = ["%s = '%s%s'" % (к, з.replace("'", "''"), хвост)
             for к, з in zip(('ru', 'fr', 'en', 'es'), значения)]
    одной = 'НСтр("' + '; '.join(части) + '")'
    if len('\t\tШаблон = ' + одной + ';') <= 140:
        return одной
    # Длинная строка разбивается по языкам: продолжение НСтр начинается с "|".
    return 'НСтр("' + ';\n\t\t\t|'.join(части) + '")'


def конец_блока(t, s, тег):
    г = 0
    for m in re.finditer(r'<%s\b|</%s>' % (тег, тег), t[s:]):
        г += 1 if not m.group(0).startswith('</') else -1
        if г == 0:
            return s + m.end()
    raise ValueError(тег)


def блок(t, тег, имя):
    m = re.search(r'<%s\b[^>]*>\s*<name>%s</name>' % (тег, re.escape(имя)), t)
    return (m.start(), конец_блока(t, m.start(), тег)) if m else None


def удалить_блок(t, тег, имя):
    b = блок(t, тег, имя)
    if not b:
        return t
    s, e = b
    ls = t.rfind('\n', 0, s)
    if t[ls + 1:s].strip() == '':
        s = ls
    return t[:s] + t[e:]


def перенумеровать(фрагмент, счётчик):
    def repl(_):
        счётчик[0] += 1
        return '<id>%d</id>' % счётчик[0]
    return re.sub(r'<id>-?\d+</id>', repl, фрагмент)


