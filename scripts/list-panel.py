def построить_модуль(документ, конф):
    m = читать(ЭТАЛОН / 'Module.bsl')
    m = m.replace('ДокументСсылка.РеализацияТоваровУслуг', 'ДокументСсылка.' + документ)
    m = m.replace('Документ.РеализацияТоваровУслуг', 'Документ.' + документ)
    m = re.sub(r'// Создаёт реализации по выделенным заказам.*?КонецПроцедуры\n\n', '', m, flags=re.S)
    m = re.sub(r'// Создаёт и записывает реализации по заказам.*?КонецФункции\n\n', '', m, flags=re.S)
    m = m.replace('''&НаКлиенте
Процедура ФильтрОперацииПриИзменении(Элемент)

	ПрименитьФильтрОперации();

КонецПроцедуры

''', '')
    m = re.sub(r'// Отбирает список по виду хозяйственной операции.*?КонецФункции\n\n', '', m, flags=re.S)
    # Отбор по операции - специфика эталона: у клонов тумблера операции нет.
    m = re.sub(r'\tОперация = ОперацияФильтра\(\);\n\tЕсли Операция <> Неопределено Тогда\n'
               r'\t\tУсловия\.Добавить\([^\n]*\n\t\tЗапрос\.УстановитьПараметр\([^\n]*\n\tКонецЕсли;\n', '', m)

    # ПриСозданииНаСервере: тело прежнего модуля сохраняется (параметры динсписка,
    # принудительные отборы по роли), к нему добавляется инициализация страниц.
    прежний = КОРЕНЬ / f'Documents/{документ}/Forms/ФормаСписка/Module.bsl'
    тело = ''
    if прежний.exists():
        s = re.search(r'Процедура ПриСозданииНаСервере\([^)]*\)\n(.*?)КонецПроцедуры', читать(прежний), re.S)
        if s:
            тело = s.group(1).rstrip('\n') + '\n'
    m = re.sub(r'(Процедура ПриСозданииНаСервере\([^)]*\)\n).*?(\tНомерСтраницы = 1;)',
               lambda mm: mm.group(1) + тело + mm.group(2), m, flags=re.S)

    поле_контрагента = конф.get('поле_контрагента', 'Контрагент')
    if поле_контрагента != 'Контрагент':
        m = m.replace('\tОтборы.Вставить("Контрагент", ОтборКонтрагент);',
                      '\tОтборы.Вставить("%s", ОтборКонтрагент);' % поле_контрагента)
        m = m.replace('\t\tУсловия.Добавить("Док.Контрагент = &Контрагент");',
                      '\t\tУсловия.Добавить("Док.%s = &Контрагент");' % поле_контрагента)
    for поле, реквизит in СПРАВОЧНЫЕ.items():
        if поле in конф['фильтры']:
            continue
        m = m.replace('\tОтборы.Вставить("%s", %s);\n' % (поле, реквизит), '')
        m = re.sub(r'\tЕсли ЗначениеЗаполнено\(%s\) Тогда\n\t\tУсловия\.Добавить\([^\n]*\n'
                   r'\t\tЗапрос\.УстановитьПараметр\([^\n]*\n\tКонецЕсли;\n' % реквизит, '', m)
    # Принудительный склад по роли остаётся только там, где фильтр склада есть.
    if 'МестоХранения' in конф['фильтры']:
        m = m.replace('''	СкладОтбора = ОтборСклад;
	// BSLLS:IsInRoleMethod-off - тот же принудительный отбор склада, что и в ПриСозданииНаСервере.
	Если Не ЗначениеЗаполнено(СкладОтбора) И РольДоступна("PDV") Тогда
		СкладОтбора = РегистрыСведений.НастройкиПользователей.СкладПользователя();
	КонецЕсли;
	// BSLLS:IsInRoleMethod-on
	Если ЗначениеЗаполнено(СкладОтбора) Тогда''', '''	Если ЗначениеЗаполнено(ОтборСклад) Тогда''')
        m = m.replace('\t\tЗапрос.УстановитьПараметр("Склад", СкладОтбора);', '\t\tЗапрос.УстановитьПараметр("Склад", ОтборСклад);')
    else:
        m = re.sub(r'\tСкладОтбора = ОтборСклад;\n.*?Запрос\.УстановитьПараметр\("Склад", СкладОтбора\);\n\tКонецЕсли;\n',
                   '', m, flags=re.S)

    if not конф['долг']:
        m = m.replace('\tУстановитьОтборПоПолю("Долг", ОтборДолг, ВидСравненияУсловия(ОтборДолгУсловие));\n', '')
        m = re.sub(r'\t// Долг документа - остаток взаиморасчётов.*?\tКонецЕсли;\n\n', '', m, flags=re.S)
        m = m.replace('\tТекстСоединения = "";\n', '')
        m = m.replace(' + ТекстСоединения + ТекстУсловий', ' + ТекстУсловий')
    if not конф['клиент']:
        m = re.sub(r'&НаКлиенте\nПроцедура ПоказатьКлиента\(Команда\)\n.*?КонецПроцедуры\n\n', '', m, flags=re.S)

    m = re.sub(r'// Правая панель:.*?КонецПроцедуры\n', сведения(документ, конф), m, flags=re.S)
    m = re.sub(r'\n{3,}', '\n\n', m)
    return КОРЕНЬ / f'Documents/{документ}/Forms/ФормаСписка/Module.bsl', m


def main():
    арг = sys.argv[1:]
    записывать = '--применить' in арг
    документы = [a for a in арг if not a.startswith('--')]
    if not документы:
        print(__doc__)
        return 1
    import xml.etree.ElementTree as ET
    for д in документы:
        конф = КОНФИГ[д]
        pf, форма = построить_форму(д, конф)
        pm, модуль = построить_модуль(д, конф)
        ET.fromstring(форма.encode('utf-8'))
        assert 'ОперацияФильтра' not in модуль and 'СкладОтбора' not in модуль, д
        print(f'{д}: форма {len(форма)} символов, модуль {модуль.count(chr(10))} строк')
        if записывать:
            if pm.exists():
                pm.with_suffix('.bsl.orig').write_text(читать(pm), encoding='utf-8')
            pf.write_text(форма, encoding='utf-8')
            pm.write_text(модуль, encoding='utf-8')
            print('  записано')
    return 0


