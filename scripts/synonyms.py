#!/usr/bin/env python3
"""Приводит синонимы реквизитов документов к единому словарю на четырёх языках.

Словарь — `scripts/synonyms-dict.json`: как называется реквизит по-русски,
по-французски, по-английски и по-испански во всей конфигурации, и где название
осознанно своё (контрагент в продаже — «Клиент», в закупке — «Поставщик»,
место хранения в перемещении — «Списать с»).

Правка точечная, по тексту `.mdo`: меняется только `<value>` внутри `<synonym>`
нужного реквизита, остальной файл не переписывается. Реквизиты табличных частей
не трогаются — в реализации и поступлении есть свой `Контрагент` в ТЧ
дополнительных расходов, и там это перевозчик.

Использование:
  scripts/synonyms.py                  показать, что изменится
  scripts/synonyms.py --применить      записать
"""
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДОКУМЕНТЫ = КОРЕНЬ / 'src' / 'cf' / 'src' / 'Documents'
СЛОВАРЬ = Path(__file__).resolve().parent / 'synonyms-dict.json'
ЯЗЫКИ = ('ru', 'fr', 'en', 'es')

СИНОНИМ = re.compile(r'([ \t]*)<synonym>\s*<key>(\w+)</key>\s*<value>([^<]*)</value>\s*</synonym>')


def экранировать(значение):
    return значение.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def диапазоны_тч(текст):
    """Границы блоков табличных частей — их реквизиты словарём не правятся."""
    границы = []
    for м in re.finditer(r'<tabularSections[ >]', текст):
        конец = текст.find('</tabularSections>', м.start())
        if конец > 0:
            границы.append((м.start(), конец))
    return границы


def реквизиты(текст):
    """Блоки <attributes> верхнего уровня: (имя, начало, конец)."""
    тч = диапазоны_тч(текст)
    for м in re.finditer(r'<attributes[ >]', текст):
        если_в_тч = any(н <= м.start() <= к for н, к in тч)
        if если_в_тч:
            continue
        конец = текст.find('</attributes>', м.start())
        if конец < 0:
            continue
        блок = текст[м.start():конец]
        имя = re.search(r'<name>([^<]*)</name>', блок)
        if имя:
            yield имя.group(1), м.start(), конец


def заменить_синонимы(блок, цель):
    """Значения <synonym> приводятся к цели; недостающий язык добавляется по образцу соседнего.

    Форматирование не трогается: переписывается только текст внутри <value>, а новый
    блок собирается с отступами существующего — иначе в дифф попадает перевыравнивание.
    """
    найденные = list(СИНОНИМ.finditer(блок))
    новый = блок
    for м in reversed(найденные):
        язык = м.group(2)
        если_надо = цель.get(язык)
        if если_надо is None or м.group(3) == экранировать(если_надо):
            continue
        начало_значения = м.start(3)
        новый = новый[:начало_значения] + экранировать(если_надо) + новый[м.end(3):]
    есть = {м.group(2) for м in найденные}
    нехватка = [я for я in ЯЗЫКИ if я in цель and я not in есть]
    if нехватка and найденные:
        отступ = найденные[-1].group(1)
        for язык in нехватка:
            последний = list(СИНОНИМ.finditer(новый))[-1]
            готовый = ('\n%s<synonym>\n%s  <key>%s</key>\n%s  <value>%s</value>\n%s</synonym>'
                       % (отступ, отступ, язык, отступ, экранировать(цель[язык]), отступ))
            новый = новый[:последний.end()] + готовый + новый[последний.end():]
    return новый


def текущие(блок):
    return {м.group(2): м.group(3) for м in СИНОНИМ.finditer(блок)}


def main(argv):
    применить = '--применить' in argv
    словарь = json.loads(СЛОВАРЬ.read_text(encoding='utf-8'))
    общие, по_документам = словарь['общие'], словарь['по_документам']
    без_изменений = словарь['без_изменений']
    правок = 0
    файлов = 0
    for mdo in sorted(ДОКУМЕНТЫ.glob('*/*.mdo')):
        документ = mdo.stem
        текст = mdo.read_text(encoding='utf-8')
        новый = текст
        сдвиг = 0
        свои = по_документам.get(документ, {})
        пропустить = set(без_изменений.get(документ, []))
        изменения = []
        for имя, начало, конец in реквизиты(текст):
            if имя in пропустить or (имя not in общие and имя not in свои):
                continue
            цель = dict(общие.get(имя, {}))
            цель.update(свои.get(имя, {}))
            блок = текст[начало:конец]
            было = текущие(блок)
            if all(было.get(я, '') == цель.get(я, было.get(я, '')) for я in ЯЗЫКИ):
                continue
            стало_блок = заменить_синонимы(блок, цель)
            if стало_блок == блок:
                continue
            новый = новый[:начало + сдвиг] + стало_блок + новый[конец + сдвиг:]
            сдвиг += len(стало_блок) - len(блок)
            изменения.append((имя, было, цель))
        if not изменения:
            continue
        файлов += 1
        правок += len(изменения)
        print('%s' % документ)
        for имя, было, цель in изменения:
            разница = ', '.join('%s: %r -> %r' % (я, было.get(я, ''), цель[я])
                                for я in ЯЗЫКИ if я in цель and было.get(я, '') != цель[я])
            print('    %-30s %s' % (имя, разница))
        if применить:
            mdo.write_text(новый, encoding='utf-8')
    print('\nреквизитов правится: %d в %d документах%s'
          % (правок, файлов, '' if применить else ' (показ, без записи)'))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
